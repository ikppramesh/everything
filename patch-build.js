// ── Patching logic ─────────────────────────────────────────────────────────
const buildPath = path.join(__dirname, 'build.js');
let src = fs.readFileSync(buildPath, 'utf8');

let patched = 0;
for (const [id, data] of Object.entries(ND)) {
  // Find the solution entry by id
  const idMarker = `id: '${id}'`;
  const idx = src.indexOf(idMarker);
  if (idx === -1) { console.warn(`⚠️  Not found: ${id}`); continue; }

  // Find chartData: {...} after this solution's id
  const chartStart = src.indexOf('chartData:', idx);
  if (chartStart === -1) { console.warn(`⚠️  No chartData for: ${id}`); continue; }

  // Find end of chartData object (closing } of data array then })
  let depth = 0, pos = chartStart;
  while (pos < src.length) {
    if (src[pos] === '{') depth++;
    else if (src[pos] === '}') { depth--; if (depth === 0) { pos++; break; } }
    pos++;
  }

  // Check if new fields already exist (avoid double-patching)
  const snippet = src.slice(idx, pos + 200);
  if (snippet.includes('useCase:')) { console.log(`⏭️  Already patched: ${id}`); patched++; continue; }

  // Build insertion string
  const ins = `,
    useCase: ${JSON.stringify(data.useCase)},
    difficulty: ${JSON.stringify(data.difficulty)},
    tableColumns: ${JSON.stringify(data.tableColumns)},
    mockRows: ${JSON.stringify(data.mockRows)},
    features: ${JSON.stringify(data.features)},
    stack: ${JSON.stringify(data.stack)},
    integrations: ${JSON.stringify(data.integrations)}`;

  src = src.slice(0, pos) + ins + src.slice(pos);
  patched++;
  console.log(`✅  Patched: ${id}`);
}

fs.writeFileSync(buildPath, src, 'utf8');
console.log(`\n🎉 Done — patched ${patched} solutions in build.js`);
